/**
 * С какого понедельника начинается отсчёт проектов. Нужен, чтобы проекты шли
 * по порядку списка — от простого меча к роботу, — а не с середины, куда
 * попал бы отсчёт от календарного номера недели.
 *
 * Хочешь начать список заново — поставь сюда дату нужного понедельника.
 * В эту неделю дети получат ПЕРВЫЙ проект списка, дальше по порядку.
 *
 * 28.07.2026 отсчёт сдвинут на понедельник 27 июля — решение владельца:
 * «с сегодняшнего дня делаем отсчёт по проектам с меча». Причина простая:
 * на примере МЕЧА снят рилс, и ребёнок из рекламы должен увидеть то самое,
 * что ему показали. До этого неделя 27 июля отдавала уже второй проект.
 */
const ROTATION_START_MONDAY = "2026-07-27";

/**
 * ЗАКРЕПЛЕНИЯ ПРОЕКТА БОЛЬШЕ НЕТ. С 27 по 28 июля тут стояла отдельная
 * строка `PINNED_PROJECT_ID`: она выдавала ВСЕМ детям меч в любую неделю,
 * пока идёт рилс, и ротацию при этом выключала совсем.
 *
 * Убрана 28.07 по решению владельца: то же самое делает сдвиг даты выше,
 * только честно — меч идёт первой неделей, а дальше список едет сам,
 * и нечего забывать вернуть обратно. Двух рычагов на один проект недели
 * быть не должно.
 */

/**
 * Подмена проекта ИЗ ПАНЕЛИ ВЛАДЕЛЬЦА — только на его собственном телефоне.
 *
 * Живёт в памяти устройства, а не в сторе: это не прогресс, в облако его
 * тащить незачем, и синхронить два места тоже незачем. Дети об этом ключе
 * не знают и знать не могут.
 *
 * Нужна для съёмок и проверки: посмотреть любой проект, не дожидаясь его
 * недели и не выкладывая сайт.
 */
const DEV_PROJECT_KEY = "bb_dev_project_v1";

export function getDevProjectId(): string | null {
  try {
    return window.localStorage.getItem(DEV_PROJECT_KEY);
  } catch {
    // Нет доступа к памяти (или мы вообще не в браузере) — подмены нет.
    return null;
  }
}

export function setDevProjectId(projectId: string | null) {
  try {
    if (projectId) window.localStorage.setItem(DEV_PROJECT_KEY, projectId);
    else window.localStorage.removeItem(DEV_PROJECT_KEY);
  } catch {
    // Не записалось — переключатель просто не сработает, ничего не сломается.
  }
}

const WEEK_MS = 7 * 24 * 60 * 60 * 1000;

// Каждый проект рассчитан на пять шагов — по одному на будний день.
// Отсюда «последний шаг» в календаре ниже.
const STEPS_PER_WEEK = 5;
const LAST_STEP_INDEX = STEPS_PER_WEEK - 1;

/**
 * Проект недели: по кругу, чтобы у всех в одну неделю был один и тот же.
 *
 * Порядок старшинства, сверху вниз:
 * 1. подмена из панели владельца — только на его телефоне;
 * 2. обычная ротация по неделям — то, что видят дети.
 *
 * Несуществующий id молча игнорируется: опечатка в подмене не должна
 * оставлять ребёнка вообще без проекта.
 */
export function getWeekProject(weekCycleKey: string): WeeklyProject {
  const forcedId = getDevProjectId();

  if (forcedId) {
    const forced = WEEKLY_PROJECTS.find((project) => project.id === forcedId);
    if (forced) return forced;
  }

  return getChildrenWeekProject(weekCycleKey);
}

/**
 * Ровно та же ротация, но БЕЗ подмены из панели владельца — то есть то,
 * что в эту неделю получают дети. Нужна одному месту: панель владельца
 * показывает эту строку, чтобы владелец не спутал свой телефон с общим.
 */
export function getChildrenWeekProject(weekCycleKey: string): WeeklyProject {
  const weekDate = weekCycleKey.replace("weekly-", "");
  const weeksPassed = Math.round(
    (new Date(weekDate).getTime() - new Date(ROTATION_START_MONDAY).getTime()) /
      WEEK_MS
  );

  if (!Number.isFinite(weeksPassed)) return WEEKLY_PROJECTS[0];

  // Остаток от деления в JS может быть отрицательным — поправляем,
  // иначе недели до стартовой даты дали бы пустой проект.
  const count = WEEKLY_PROJECTS.length;
  const index = ((weeksPassed % count) + count) % count;

  return WEEKLY_PROJECTS[index];
}

/**
 * Выходной ли это день.
 *
 * Шаги проекта выдаются ТЕПЕРЬ КАЖДЫЙ ДЕНЬ, включая выходные. От этой функции
 * зависит только ВТОРОЕ задание дня: в будни это разминка на пять минут,
 * в выходные — задание на насмотренность (смотреть и разбирать, а не моделить).
 *
 * Раньше здесь была `isProjectDay`, и она в субботу с воскресеньем убирала
 * шаг проекта совсем. Из-за этого ребёнок, севший за проект в выходные,
 * не мог сдать ни одного шага: во вкладке «Неделя» шаг честно горел «сейчас»,
 * а во вкладке «День» его просто не было. Замечание владельца 25.07.
 */
export function isWeekend(dateKey: string): boolean {
  const weekday = parseLocalDate(dateKey).getDay(); // 0 = воскресенье

  return weekday === 0 || weekday === 6;
}

/**
 * Докуда календарь открыл шаги СЕГОДНЯ — номер последнего доступного шага.
 *
 * Будни держат темп «шаг в день»: понедельник открывает только первый шаг,
 * среда — первые три. Вперёд паровоза не убежишь, иначе весь проект
 * закрывается в понедельник вечером и неделя перестаёт быть неделей.
 * При этом отставший НАГОНЯЕТ: пришёл в среду — делает первый, второй
 * и третий подряд, по мере того как куратор их принимает.
 *
 * Суббота и воскресенье открывают ВСЕ пять. Выходные отданы под догон:
 * проект заканчивается в воскресенье, в понедельник начинается следующий,
 * и тот, кто смог сесть только в воскресенье, должен успеть сделать его
 * целиком. Решение владельца 25.07: «большинство откладывает на последний
 * момент, будут дети, кто только в воскресенье сядет на несколько часов».
 */
export function getPaceIndex(dateKey: string): number {
  const weekday = parseLocalDate(dateKey).getDay(); // 0 = воскресенье

  if (isWeekend(dateKey)) return LAST_STEP_INDEX;

  return Math.min(LAST_STEP_INDEX, Math.max(0, weekday - 1));
}

/**
 * ОЧЕРЕДЬ ДЕРЖИТСЯ ВСЕГДА, все семь дней. Шаг, отправленный куратору,
 * закрывает следующий до тех пор, пока куратор не ответит.
 *
 * Причина: шаги строятся друг на друге. «Покрась клинок» поверх заточки,
 * которую куратор ещё не принял, — это работа поверх, возможно, брака.
 *
 * ИСТОРИЯ, чтобы никто не переоткрывал. 25.07 это правило на выходные
 * попробовали снять: рассуждение было «в выходные календарь открыл все пять,
 * и ожидание куратора становится единственной стеной для того, кто сел
 * за проект в воскресенье». Владелец согласился, мы выложили — и он тут же
 * проверил на живом боте и отменил: «я могу насдавать кучу шагов, они будут
 * лежать на проверке, а каждый следующий открывается сразу же. Должно быть,
 * что только после проверки, ДАЖЕ ЕСЛИ ребёнок подключился в конце недели».
 * Смысл проверки в том, что она гейт, а не отметка постфактум.
 *
 * Календарь и очередь — две РАЗНЫЕ двери, обе должны быть открыты:
 * календарь (getPaceIndex) говорит, сколько шагов открыто сегодня,
 * очередь говорит, что предыдущий уже принят.
 */
export type StepState = "done" | "pending" | "next" | "soon" | "locked";

/**
 * Состояние каждого шага для карточки недели.
 *
 * Шаги открываются ПО ПОРЯДКУ, а не по дням календаря. Раньше во вторник
 * выдавался «шаг 2», и тот, кто пришёл в середине недели, не мог сделать
 * первый — он был потерян навсегда. Теперь день недели ни на что не влияет:
 * следующий шаг — просто первый несданный. Отстал — нагоняешь, награда та же,
 * а за ежедневность и так платит бонус серии.
 *
 * «pending» — отправлен куратору и ДЕРЖИТ ОЧЕРЕДЬ: пока шаг не проверен,
 * следующий не открывается, в любой день недели. Причина — в шапке над
 * StepState.
 */
export function getStepStates(
  project: WeeklyProject,
  doneIds: string[],
  pendingIds: string[],
  // Докуда открыл календарь: дальше сегодня не уйти (см. getPaceIndex).
  openUpTo: number = project.steps.length - 1
): StepState[] {
  let blocked = false;

  return project.steps.map((step, index) => {
    if (doneIds.includes(step.id)) return "done";

    if (pendingIds.includes(step.id)) {
      // Шаг у куратора — всё, что за ним, ждёт его ответа.
      blocked = true;
      return "pending";
    }

    if (blocked) return "locked";

    blocked = true;

    // Очередь дошла, а календарь — ещё нет: это «завтра», а не «сейчас».
    return index <= openUpTo ? "next" : "soon";
  });
}

/**
 * Шаг, который делаем сейчас: первый несданный — но только если он не стоит
 * у куратора. Стоит — значит делать сегодня нечего, и экран говорит об этом
 * словами (см. getWaitingStep). Так во все дни недели, включая выходные.
 */
export function getNextStep(
  project: WeeklyProject,
  doneIds: string[],
  pendingIds: string[]
) {
  const index = project.steps.findIndex((step) => !doneIds.includes(step.id));

  if (index === -1) return null;
  if (pendingIds.includes(project.steps[index].id)) return null;

  return { step: project.steps[index], index };
}

/**
 * Шаг, который стоит у куратора и держит очередь. Нужен экрану, чтобы сказать
 * ребёнку правду: не «на сегодня всё», а «жду ответа по шагу N».
 */
export function getWaitingStep(
  project: WeeklyProject,
  doneIds: string[],
  pendingIds: string[]
) {
  const index = project.steps.findIndex((step) => !doneIds.includes(step.id));

  if (index === -1) return null;
  if (!pendingIds.includes(project.steps[index].id)) return null;

  return { step: project.steps[index], index };
}
