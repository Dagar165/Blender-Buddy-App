/**
 * ОБУЧАЮЩИЙ ТУР ПРИ ПЕРВОМ ЗАПУСКЕ (владелец правит тексты сам).
 *
 * Зачем он есть. Два разных человека, увидевшие приложение впервые — владелец
 * и 14-летний тестировщик, — сказали одно и то же: «непонятно, куда тыкать».
 * Оранжевая строка на главном экране лечит только задания; про поглаживание,
 * про серию дней, про то, что призрака надо кормить, ребёнок не узнавал
 * ниоткуда. Тур проходится один раз и объясняет ровно это.
 *
 * Все шаги живут на ГЛАВНОМ экране нарочно: тур, который сам переключает
 * вкладки, ребёнок теряет из виду и пугается. Нижние вкладки видны с главной,
 * поэтому рассказать про них можно, никуда не уходя.
 *
 * Что можно менять свободно: title, text, порядок шагов, их количество.
 * Что менять НЕЛЬЗЯ: значения target — это метки в коде экранов
 * (`data-tour="..."`), по ним тур находит, что подсветить. Неизвестная метка
 * не ломает приложение: шаг просто покажется без подсветки, посреди экрана.
 *
 * Хочешь показать тур ЗАНОВО всем, кто его уже прошёл, — поменяй VERSION.
 */

