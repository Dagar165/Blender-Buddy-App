/**
 * Числовые id — второй способ узнать своего, и он НАДЁЖНЕЕ ника.
 *
 * Ник в Телеграме человек может поменять себе сам за десять секунд,
 * и в тот же миг панель у него пропадёт — а он даже не поймёт, почему.
 * Числовой id не меняется никогда. Поэтому у тех, кто работает с панелью
 * постоянно, лучше держать оба: сработает любой из них.
 */
export const DEV_USER_IDS: number[] = [
  787649257, // Dmitrshal
];

export const isDevUser = (
  telegramUserId: number | null,
  telegramUsername: string | null
): boolean => {
  // Вне Telegram (обычный браузер) панель открыта — там нет учеников,
  // это режим разработки.
  if (telegramUserId === null && telegramUsername === null) return true;

  if (telegramUserId !== null && DEV_USER_IDS.includes(telegramUserId)) {
    return true;
  }

  if (telegramUsername) {
    const normalized = telegramUsername.replace(/^@/, "").toLowerCase();

    return DEV_USERNAMES.some(
      (name) => name.replace(/^@/, "").toLowerCase() === normalized
    );
  }

  return false;
};
