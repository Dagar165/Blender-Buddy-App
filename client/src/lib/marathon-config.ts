/**
 * Как часто вместо совета по Blender показывать факт о марафоне.
 *
 * 4 — примерно каждый четвёртый раз. Больше НЕ делать: мини-игру открывают
 * часто, и если марафон будет вылезать через раз, ребёнок перестанет читать
 * эту строчку вообще — вместе с советами по Blender.
 */
export const MARATHON_FACT_EVERY = 4;

/**
 * Что показать под игрой: факт о марафоне или ничего (тогда будет совет).
 * `seed` — любое растущее число (номер партии).
 */
export function pickMarathonFact(seed: number): string | null {
  if (MARATHON_FACTS.length === 0) return null;

  const safeSeed = Math.abs(Math.floor(seed));

  if (safeSeed % MARATHON_FACT_EVERY !== 0) return null;

  const index = Math.floor(safeSeed / MARATHON_FACT_EVERY) % MARATHON_FACTS.length;

  return MARATHON_FACTS[index];
}

