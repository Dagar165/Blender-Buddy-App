/**
 * КАКОЙ СОВЕТ ВЫДАТЬ. Порядок перемешан, повторов внутри круга нет.
 *
 * Было сломано так (владелец 25.07: «выпадают одни и те же в одной и той же
 * последовательности, тогда нет смысла тапать по призраку»): советы брались
 * из списка ПОДРЯД — `BLENDER_TIPS[cursor % 40]`, а `cursor` рос на единицу.
 * То есть порядок был всегда один — порядок строк в файле, — менялось лишь
 * место старта. А после сброса прогресса старт был 0, и первые советы
 * повторялись слово в слово; владелец во время проверок сбрасывался часто
 * и поэтому видел одно и то же особенно ярко.
 *
 * Как теперь. Сорок советов — это КРУГ. На каждый круг список перемешивается
 * заново, и за круг каждый совет выпадает ровно один раз: не бывает ни
 * «два одинаковых подряд», ни «сорок раз мимо любимого». Перемешивание
 * зависит только от номера круга, поэтому оно не «дрожит» при перезагрузке:
 * закрыл приложение, открыл — порядок тот же, ничего не потерялось.
 *
 * Чистая случайность тут была бы хуже: она даёт повторы через два-три раза
 * (это тот же парадокс, из-за которого в плеере «случайный порядок» без
 * памяти кажется сломанным).
 *
 * Владельцу: строки можно свободно добавлять и убирать, код трогать не надо.
 */
export function pickTip(cursor: number): string {
  const size = BLENDER_TIPS.length;

  if (size === 0) return "";

  const safeCursor = Math.max(0, Math.floor(cursor));
  const round = Math.floor(safeCursor / size);
  const position = safeCursor % size;

  return BLENDER_TIPS[orderForRound(round, size)[position]];
}

// Перемешанный порядок номеров на один круг. Семечко — номер круга,
// поэтому один и тот же круг всегда раскладывается одинаково.
function orderForRound(round: number, size: number): number[] {
  const order = Array.from({ length: size }, (_, index) => index);
  const random = createRandom((round + 1) * 0x9e3779b1);

  for (let i = size - 1; i > 0; i -= 1) {
    const j = Math.floor(random() * (i + 1));
    [order[i], order[j]] = [order[j], order[i]];
  }

  return order;
}
