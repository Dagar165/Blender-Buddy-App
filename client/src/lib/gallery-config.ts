/** Плоский список всех работ подряд, в порядке из `GALLERY_AUTHORS`. */
export type GalleryItem = GalleryWork & { nick: string };

export function getGalleryItems(): GalleryItem[] {
  return GALLERY_AUTHORS.flatMap((author) =>
    author.works.map((work) => ({ ...work, nick: author.nick }))
  );
}

/**
 * Адрес картинки.
 *
 * ⚠️ ПОЧЕМУ ТУТ `import.meta.env.BASE_URL`, А НЕ ПРОСТО "/gallery/...".
 * Приложение живёт НЕ в корне сайта, а по адресу
 * `dagar165.github.io/Blender-Buddy-App/`. Ссылка, начинающаяся со слэша,
 * ушла бы в корень github.io — и картинки просто не нашлись бы.
 * `BASE_URL` подставляет правильное начало и на живом сайте, и локально.
 *
 * `small` — превью для сетки (весит в разы меньше). Крупную грузим только
 * тогда, когда работу открыли.
 */
export function galleryImageUrl(file: string, small: boolean): string {
  return (
    import.meta.env.BASE_URL + "gallery/" + file + (small ? "-small" : "") + ".webp"
  );
}
